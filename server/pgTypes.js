// ============================================================================
// PostgreSQL 型別解析設定
// ----------------------------------------------------------------------------
// DATE 欄位（進貨日期、安裝日期、保固到期…）記的是「哪一天」，沒有時間、
// 也沒有時區。node-postgres 預設卻把它轉成 JS Date，而且是「本機時區的午夜」。
//
// 那個 Date 一旦經過 JSON 送到瀏覽器，就會變成 UTC 字串：
//
//   資料庫 2026-09-21
//     → pg 回傳 Date(2026-09-21 00:00 +08:00)
//     → JSON.stringify 得到 "2026-09-20T16:00:00.000Z"
//     → 前端 .slice(0, 10) 取到 "2026-09-20"
//
// 在 UTC+8 每一個日期都會早一天。進貨單的日期改了卻好像沒變，就是這個原因：
// 存進去是對的，讀出來顯示成前一天，看起來就像沒存到。
//
// 解法是不要轉：DATE 直接以 'YYYY-MM-DD' 字串回傳，跟資料庫裡看到的一致。
// 這樣不論在哪個時區、不論有沒有經過 JSON，都是同一個值。
//
// 只影響 DATE (1082)。TIMESTAMP 仍然照原本的方式處理 —— 它確實代表一個時間點。
// ============================================================================

import pg from 'pg';

/** PostgreSQL 的 DATE 型別代碼 */
const DATE_OID = 1082;

/**
 * 套用型別解析設定。伺服器與 Electron 兩條路徑都要呼叫，
 * 否則同一筆資料在兩邊會差一天。
 */
export function applyPgTypeParsers() {
  pg.types.setTypeParser(DATE_OID, (value) => value);
}

applyPgTypeParsers();

export default applyPgTypeParsers;
