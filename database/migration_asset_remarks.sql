-- ============================================================================
-- 資產備註欄位
-- ----------------------------------------------------------------------------
-- 設備與硬體列表新增「備註」欄位，供人工註記與批次匯入寫入。
--
-- 採用獨立的資料表欄位而非塞進 custom_attributes：
-- 備註是每筆資產都會用到的固定欄位，放在欄位中可直接搜尋、排序與匯出，
-- 也不會與 custom_attributes 內既有的 server_sn、order_source 等鍵混在一起。
--
-- 具冪等性，可重複執行。
-- ============================================================================

BEGIN;

ALTER TABLE assets ADD COLUMN IF NOT EXISTS remarks TEXT;

COMMENT ON COLUMN assets.remarks IS '備註（人工註記，亦可由批次匯入寫入）';

COMMIT;
