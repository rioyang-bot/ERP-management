-- ============================================================================
-- 出貨單：End-user 欄位
-- ----------------------------------------------------------------------------
-- 新增出貨單時填寫 End-user（最終使用者，可能與下單的客戶不同）。
-- 單頭記一份，編輯時帶回；單上的設備／硬體（含搭載的硬體）一併寫入資產的 End-user。
--
-- 具冪等性，可重複執行。
-- ============================================================================

BEGIN;

ALTER TABLE outbound_requests ADD COLUMN IF NOT EXISTS end_user VARCHAR(255);
COMMENT ON COLUMN outbound_requests.end_user IS '出貨單的 End-user，建單時一併寫入單上設備／硬體的 End-user';

COMMIT;
