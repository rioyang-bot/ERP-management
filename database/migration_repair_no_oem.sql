-- 維修單：不需送回原廠
-- ----------------------------------------------------------------------------
-- 並非每一張維修單都要送原廠。IT 人員自行排除故障的情形，先前沒有對應的
-- 路徑可走 —— 流程固定是 現場處理 → 送修原廠 → 原廠返還 → 完工出貨，
-- 不送原廠的單就卡在第一階段，永遠結不了案。
--
-- 這個旗標記錄「這張單不送原廠」，列表與詳情都看得出來，
-- 送修原廠的按鈕會收起來，改為自行維修完工。
--
-- 具冪等性，可重複執行。
-- ============================================================================

ALTER TABLE repair_orders
  ADD COLUMN IF NOT EXISTS no_oem_required BOOLEAN NOT NULL DEFAULT FALSE;
