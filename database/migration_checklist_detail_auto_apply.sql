-- ----------------------------------------------------------------------------
-- 有些細項（例如 OS、BMC IP）每一台都要填，逐台加進去太費工。
-- 勾選之後，該細項就跟主要檢查功能一樣自動出現在所有符合廠牌的設備上，
-- 但仍然是細項 —— 在設備上填寫內容而不是勾選完成。
--
-- 主要檢查功能一律自動套用，不受這個欄位影響。
-- 具冪等性，可重複執行。
-- ============================================================================

ALTER TABLE checklist_items ADD COLUMN IF NOT EXISTS auto_apply BOOLEAN DEFAULT FALSE;
