-- ============================================================================
-- 公司資產編號
-- ----------------------------------------------------------------------------
-- 列為公司資產的設備會另外掛一組財產編號（Asset No），與出廠序號是兩回事：
-- 序號是製造商給的，資產編號是公司自己編的，盤點與財產清冊對的是後者。
--
-- 先前系統沒有這個欄位，只能寫在備註裡，既搜尋不到也印不出來。
--
-- 做成實體欄位而不是塞進 custom_attributes：這是會被搜尋、會出現在列表上的
-- 識別碼，與 end_user、remarks 同一類，沿用相同的作法。
--
-- 不加唯一鍵：既有資料尚未編號，而且編號規則由使用者自訂，
-- 現階段先允許重複，需要時再另外補一支 migration。
--
-- 具冪等性，可重複執行。
-- ============================================================================

ALTER TABLE assets ADD COLUMN IF NOT EXISTS asset_no VARCHAR(100);

-- 列表與搜尋會以資產編號查找，且只有公司資產會填
CREATE INDEX IF NOT EXISTS idx_assets_asset_no
  ON assets (asset_no)
  WHERE asset_no IS NOT NULL;
