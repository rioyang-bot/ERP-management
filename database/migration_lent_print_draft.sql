-- 打開時套用在預設內容之上；「還原預設」清掉這一份。
--
-- 具冪等性，可重複執行。
-- ============================================================================

BEGIN;

ALTER TABLE outbound_requests ADD COLUMN IF NOT EXISTS print_draft JSONB;
COMMENT ON COLUMN outbound_requests.print_draft IS '借貨申請單預覽裡修改並儲存的內容（見 src/utils/lentPrintDraft.js）';

COMMIT;
