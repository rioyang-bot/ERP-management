-- ============================================================================
-- 進貨明細的備註
-- ----------------------------------------------------------------------------
-- 備註原本只存在資產上（assets.remarks）。待確認的進貨單還沒有資產，
-- 先記在明細上，確認進貨時再寫進資產；耗材沒有資產，備註就留在明細上。
--
-- 具冪等性，可重複執行。
-- ============================================================================

BEGIN;

ALTER TABLE inbound_items ADD COLUMN IF NOT EXISTS remarks TEXT;
COMMENT ON COLUMN inbound_items.remarks IS '進貨明細的備註；確認進貨時寫進資產的 remarks';

COMMIT;
