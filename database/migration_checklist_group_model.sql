-- ============================================================================
-- 出機檢查表：主項目可再綁定型號
-- ----------------------------------------------------------------------------
-- 主項目原本只能綁廠牌，同廠牌的每一台設備都套用同一組檢查項目。
-- 但同一個廠牌底下的機種要檢查的東西不一樣，例如 LDA 的 FIREWALL、NEOTAP、
-- MUX ULTIMATE 各有各的項目。
--
-- 新增 model：
--   廠牌 + 型號   只套用到該型號的設備
--   廠牌、型號空  整個廠牌的設備都套用（與先前相同）
--   廠牌空        通用，所有設備都套用（與先前相同）
-- 同一台設備符合的主項目全部套用，例如「LDA 共通」+「LDA NEOTAP」。
--
-- 型號一定要搭配廠牌：不同廠牌可能有同名的型號。
--
-- 具冪等性，可重複執行。既有主項目的 model 為 NULL，行為不變。
-- ============================================================================

ALTER TABLE checklist_groups ADD COLUMN IF NOT EXISTS model VARCHAR(200);

COMMENT ON COLUMN checklist_groups.model IS '適用型號；留空代表整個廠牌適用。必須搭配 brand 使用';
